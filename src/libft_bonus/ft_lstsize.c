#include "mega_libft.h"

/**
 * @brief Conta gli elementi di una lista.
 *
 * @param lst Testa della lista.
 * @return int Il numero di elementi, 0 se la lista e' vuota.
 */
int	ft_lstsize(t_list *lst)
{
	int		i;
	t_list	*tmp;

	i = 0;
	tmp = lst;
	while (tmp != NULL)
	{
		tmp = tmp->next;
		i++;
	}
	return (i);
}
