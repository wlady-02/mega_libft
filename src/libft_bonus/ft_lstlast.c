#include "mega_libft.h"

/**
 * @brief Cerca l'ultimo elemento di una lista.
 *
 * @param lst Testa della lista.
 * @return t_list * L'ultimo elemento, NULL se la lista e' vuota.
 */
t_list	*ft_lstlast(t_list *lst)
{
	t_list	*tmp;

	if (lst == NULL)
		return (NULL);
	tmp = lst;
	while (tmp->next != NULL)
		tmp = tmp->next;
	return (tmp);
}
